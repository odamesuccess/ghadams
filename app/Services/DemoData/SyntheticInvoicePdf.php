<?php

namespace App\Services\DemoData;

/**
 * Minimal one-page PDF for synthetic maintenance invoices.
 *
 * The maintenance workflow requires an invoice PDF before a job can be
 * completed or paid, so every synthetic completed job gets one. Each page is
 * clearly marked as synthetic demonstration data.
 */
class SyntheticInvoicePdf
{
    public static function render(array $job, array $asset, int $jobId): string
    {
        $amount = number_format((float) $job['actual_cost'], 2);
        $status = match ($job['payment_status']) {
            'paid' => 'PAID on '.substr((string) $job['payment_date'], 0, 10).' (ref '.$job['payment_ref'].')',
            'pending' => 'PAYMENT PROCESSING - outstanding GHS '.$amount,
            default => 'UNPAID - outstanding GHS '.$amount,
        };

        $lines = [
            ['SYNTHETIC DEMONSTRATION DATA - NOT A REAL INVOICE', 13],
            ['', 11],
            ['Service invoice '.$job['invoice']['ref'], 15],
            ['Invoice date: '.$job['invoice']['date'], 11],
            ['Maintenance job #'.$jobId, 11],
            ['', 11],
            ['Asset: '.$asset['asset_code'], 11],
            ['Item: '.trim($asset['brand'].' '.($asset['model_number'] ?? '').' '.$asset['type_name']), 11],
            ['Serial: '.$asset['serial_number'], 11],
            ['', 11],
            ['Fault: '.self::clip($job['fault_description']), 11],
            ['Work done: '.self::clip((string) $job['completion_note']), 11],
            ['Completed: '.$job['actual_completion_date'], 11],
            ['', 11],
            ['Amount payable: GHS '.$amount, 13],
            ['Status: '.$status, 11],
            ['', 11],
            ['Generated by the GhanaDAMS synthetic demo dataset for testing only.', 9],
        ];

        $content = "BT\n/F1 11 Tf\n50 790 Td\n";

        foreach ($lines as [$text, $size]) {
            $content .= "/F1 {$size} Tf\n(".self::escape($text).") Tj\n0 -20 Td\n";
        }

        $content .= "ET\n";

        return self::assemble($content);
    }

    /**
     * Replace the asset code printed on an invoice this class rendered, keeping the rest.
     * Returns null when the PDF does not contain the old code.
     */
    public static function replaceAssetCode(string $pdf, string $old, string $new): ?string
    {
        if (! preg_match('/stream\n(.*?)endstream/s', $pdf, $m)) {
            return null;
        }

        $needle = '('.self::escape('Asset: '.$old).') Tj';

        if (! str_contains($m[1], $needle)) {
            return null;
        }

        return self::assemble(str_replace($needle, '('.self::escape('Asset: '.$new).') Tj', $m[1]));
    }

    private static function assemble(string $content): string
    {
        $objects = [
            '<< /Type /Catalog /Pages 2 0 R >>',
            '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
            '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
            '<< /Length '.strlen($content)." >>\nstream\n{$content}endstream",
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        ];

        $pdf = "%PDF-1.4\n";
        $offsets = [];

        foreach ($objects as $i => $object) {
            $offsets[] = strlen($pdf);
            $pdf .= ($i + 1)." 0 obj\n{$object}\nendobj\n";
        }

        $xref = strlen($pdf);
        $pdf .= 'xref
0 '.(count($objects) + 1)."\n0000000000 65535 f \n";

        foreach ($offsets as $offset) {
            $pdf .= sprintf("%010d 00000 n \n", $offset);
        }

        return $pdf.'trailer
<< /Size '.(count($objects) + 1)." /Root 1 0 R >>\nstartxref\n{$xref}\n%%EOF\n";
    }

    private static function clip(string $text): string
    {
        return mb_strlen($text) > 90 ? mb_substr($text, 0, 87).'...' : $text;
    }

    private static function escape(string $text): string
    {
        $ascii = preg_replace('/[^\x20-\x7E]/', '-', $text) ?? '';

        return str_replace(['\\', '(', ')'], ['\\\\', '\\(', '\\)'], $ascii);
    }
}
